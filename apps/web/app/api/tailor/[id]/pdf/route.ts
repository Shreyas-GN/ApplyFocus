import { NextRequest, NextResponse } from 'next/server';
import { and, eq } from 'drizzle-orm';
import { getUser } from '@/lib/auth/server';
import { db, tailoredDocuments } from '@/lib/db';
import type { CoverLetterContent, TailoredResumeContent } from '@/lib/types';

export async function GET(
  _request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const user = await getUser();
  if (!user) return NextResponse.json({ detail: 'Unauthorized' }, { status: 401 });

  const { id } = await params;
  const [doc] = await db
    .select()
    .from(tailoredDocuments)
    .where(and(eq(tailoredDocuments.id, id), eq(tailoredDocuments.userId, user.id)))
    .limit(1);

  if (!doc) return NextResponse.json({ detail: 'Not found' }, { status: 404 });

  const html =
    doc.type === 'resume'
      ? buildResumeHtml(doc.jobTitle, doc.company, doc.content as TailoredResumeContent)
      : buildCoverLetterHtml(doc.jobTitle, doc.company, doc.content as CoverLetterContent);

  return new NextResponse(html, {
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'X-Document-Type': doc.type,
    },
  });
}

function esc(s: string | null | undefined): string {
  if (!s) return '';
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function buildResumeHtml(
  jobTitle: string,
  company: string,
  content: TailoredResumeContent
): string {
  const expHtml =
    content.experience
      ?.map(
        (e) => `
    <div class="exp-item">
      <div class="exp-header">
        <strong>${esc(e.company)}</strong> &mdash; ${esc(e.title)}
        ${e.startDate ? `<span class="dates">${esc(e.startDate)}${e.endDate ? ` &ndash; ${esc(e.endDate)}` : ' &ndash; Present'}</span>` : ''}
      </div>
      <p>${esc(e.tailoredDescription)}</p>
    </div>`
      )
      .join('') ?? '';

  const skillsHtml = content.highlightedSkills?.length
    ? `<div class="skills">${content.highlightedSkills.map((s) => `<span class="skill-tag">${esc(s)}</span>`).join('')}</div>`
    : '';

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Tailored Resume &mdash; ${esc(jobTitle)} at ${esc(company)}</title>
<style>
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { font-family: Georgia, 'Times New Roman', serif; font-size: 11pt; line-height: 1.5; color: #1a1a1a; padding: 2cm; max-width: 800px; margin: 0 auto; }
  h1 { font-size: 18pt; margin-bottom: 4px; }
  h2 { font-size: 11pt; font-weight: 600; border-bottom: 1px solid #ccc; padding-bottom: 3px; margin: 18px 0 8px; text-transform: uppercase; letter-spacing: 0.05em; }
  .target { font-size: 11pt; color: #555; margin-bottom: 16px; }
  .summary-block { margin-bottom: 12px; }
  .exp-item { margin-bottom: 12px; }
  .exp-header { font-weight: 600; }
  .dates { font-weight: normal; color: #666; margin-left: 8px; font-size: 10pt; }
  .skills { display: flex; flex-wrap: wrap; gap: 6px; }
  .skill-tag { background: #f3f4f6; padding: 2px 8px; border-radius: 4px; font-size: 10pt; font-family: Arial, sans-serif; }
  .meta { font-size: 9pt; color: #888; margin-top: 24px; border-top: 1px solid #eee; padding-top: 8px; }
  @media print { body { padding: 1cm; } .meta { display: none; } }
</style>
</head>
<body>
<h1>Tailored Resume</h1>
<p class="target">Prepared for: <strong>${esc(jobTitle)}</strong> at <strong>${esc(company)}</strong></p>

${content.headline ? `<div class="summary-block"><p><strong>${esc(content.headline)}</strong></p></div>` : ''}
${content.summary ? `<div class="summary-block"><h2>Professional Summary</h2><p>${esc(content.summary)}</p></div>` : ''}
${skillsHtml ? `<div><h2>Highlighted Skills</h2>${skillsHtml}</div>` : ''}
${expHtml ? `<div><h2>Experience</h2>${expHtml}</div>` : ''}

<p class="meta">Generated by ApplyFocus &middot; Use your browser&apos;s Print &rarr; Save as PDF to download</p>
</body>
</html>`;
}

function buildCoverLetterHtml(
  jobTitle: string,
  company: string,
  content: CoverLetterContent
): string {
  const bodyHtml = content.bodyParagraphs?.map((p) => `<p>${esc(p)}</p>`).join('\n') ?? '';
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Cover Letter &mdash; ${esc(jobTitle)} at ${esc(company)}</title>
<style>
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { font-family: Georgia, 'Times New Roman', serif; font-size: 11pt; line-height: 1.6; color: #1a1a1a; padding: 2cm; max-width: 760px; margin: 0 auto; }
  h1 { font-size: 13pt; color: #555; margin-bottom: 20px; border-bottom: 1px solid #ddd; padding-bottom: 10px; }
  .greeting { font-weight: 600; margin: 20px 0 12px; }
  p { margin-bottom: 12px; }
  .closing { margin-top: 20px; }
  .signature { margin-top: 8px; font-weight: 600; }
  .meta { font-size: 9pt; color: #888; margin-top: 32px; border-top: 1px solid #eee; padding-top: 8px; }
  @media print { body { padding: 1cm; } .meta { display: none; } }
</style>
</head>
<body>
<h1>Cover Letter &mdash; ${esc(jobTitle)} at ${esc(company)}</h1>
${content.subjectLine ? `<p><strong>Subject:</strong> ${esc(content.subjectLine)}</p>` : ''}
<p class="greeting">${esc(content.greeting ?? '')}</p>
${bodyHtml}
<p class="closing">${esc(content.closing ?? '')}</p>
<p class="signature">${esc(content.signature ?? '')}</p>
<p class="meta">Generated by ApplyFocus &middot; Use your browser&apos;s Print &rarr; Save as PDF to download</p>
</body>
</html>`;
}
